/// The Contra kit's type scale. Each size pairs with a line height in
/// [AppThemeData]; sizes alone are here so a widget can ask for one number.
abstract class FontSize {
  static const double xxSmall = 11;
  static const double xSmall = 12;
  static const double small = 13;
  static const double medium = 15;
  static const double mediumLarge = 17;
  static const double large = 21;
  static const double xLarge = 24;
  static const double xxLarge = 27;
  static const double xxxLarge = 36;
  static const double display = 44;
}
